"""Audit the seven font roles on this machine and write FONT-LICENSE-REPORT.md + .cache/resolved.json.

Usage: python -P audit_fonts.py [--refresh] [--json]
  --refresh   rescan system font folders (after installing or buying a font)
"""

from __future__ import annotations

import argparse
import json
import platform
import sys
from datetime import date
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
import typography as T  # noqa: E402


def rel(p) -> str:
    if p is None:
        return "—"
    if isinstance(p, dict):
        return "<br>".join(rel(v) for v in p.values())
    if isinstance(p, list):
        return "<br>".join(rel(v) for v in p)
    pp = Path(p)
    try:
        return "typography/" + pp.relative_to(T.TYPO_DIR).as_posix()
    except ValueError:
        return f"system: `{pp.name}` (in place, never copied)"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--refresh", action="store_true")
    ap.add_argument("--json", action="store_true")
    a = ap.parse_args()
    res = T.resolve_all(refresh=a.refresh)
    T.CACHE.mkdir(exist_ok=True)
    (T.CACHE / "resolved.json").write_text(json.dumps(res, indent=2, ensure_ascii=False, default=list), encoding="utf-8")
    if a.json:
        print(json.dumps(res, indent=2, ensure_ascii=False, default=list))
        return 0
    reg = T.registry()
    lines = [
        "# Font licence report",
        "",
        f"Generated by `typography/scripts/audit_fonts.py` on {date.today().isoformat()} ({platform.system()} {platform.release()}).",
        "Re-run it on any machine that renders: the result depends on what is installed there.",
        "",
        "## A. Seven roles",
        "",
        "| Role | Requested | Renders as | State | Exact? | Licence | File / reference |",
        "|---|---|---|---|---|---|---|",
    ]
    for role, r in res.items():
        lic = r["license"] if r["exact"] else f"{r['fallback_license']} (requested font: {r['license'].split('.')[0]})"
        lines.append(f"| `{role}` | {r['requested']} | {r['resolved'] or '—'} | **{r['state']}** | {'yes' if r['exact'] else 'no — fallback'} | {lic} | {rel(r['reference'])} |")
    lines += ["", "## B. What each state means here", ""]
    for role, r in res.items():
        spec = reg["roles"][role]
        if r["state"] == "EXACT_AVAILABLE":
            msg = (f"{r['requested']} is installed on this machine and is used in place through CSS `local()`. "
                   f"The file is never copied into projects, deliveries or the repo. Elsewhere (cloud renders) the role falls back to {r['fallback_family']}.")
        elif r["state"] == "OPEN_SOURCE_INSTALLED":
            msg = f"{r['requested']} is open source (OFL) and bundled: the exact font, free for commercial video."
        elif r["state"] == "LICENSED_USER_FONT":
            msg = f"A licensed copy of {r['requested']} from fonts/private/ is used (git-ignored, never redistributed)."
        elif r["state"] == "LICENSE_REQUIRED":
            msg = (f"{r['requested']} needs a commercial licence for ads and published videos. Not bought, not downloaded. "
                   f"{r['fallback_family']} (OFL) renders instead and is labelled as the fallback. Buy: {r['purchase']}")
        elif r["state"] == "FALLBACK_ACTIVE":
            buy = f" Official purchase: {r['purchase']}" if r["purchase"] else ""
            msg = f"{r['requested']} is not installed here. {r['fallback_family']} (OFL) renders instead.{buy}"
        else:
            msg = "Neither the requested font nor its fallback file is present: run setup_fonts.py."
        lines.append(f"- **{r['requested']} → {r['resolved'] or 'nothing'}**: {msg}")
    lines += ["", "## C. Script fallbacks (Hindi / Bengali)", "",
              "The seven display faces are Latin-only. Romanised Hinglish uses them directly; Devanagari and Bengali text renders in:", ""]
    for key, s in reg["script_fallbacks"].items():
        ok = all((T.OPEN_SOURCE / v).exists() for v in s["files"].values())
        lines.append(f"- `{key}`: {s['family']} (SIL OFL 1.1) — {'installed' if ok else 'MISSING, run setup_fonts.py'}")
    lines += ["", "## D. Rights, by use", "",
              "| Use | OFL fonts (Anton, Great Vibes, Arvo, Inter, EB Garamond, Cormorant Garamond, Italianno, Noto, Hind) | System fonts used in place (Impact, …) | Blacksword |",
              "|---|---|---|---|",
              "| Rendered into your own videos / ads | yes | yes, from the machine's licensed install | only with a commercial licence |",
              "| Embedded in a web page or app | yes | no | per licence |",
              "| Redistributed (repo, editable project) | yes, with OFL.txt | **never** | **never** |",
              "| Broadcast / TV | yes | check Monotype's terms for broadcast | per licence |",
              "", "Proprietary files are referenced only through CSS `local()` / the OS font path. `fonts/private/` is git-ignored.", ""]
    out = T.TYPO_DIR / "FONT-LICENSE-REPORT.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    w = max(len(r) for r in res)
    for role, r in res.items():
        print(f"{role:{w}}  {r['requested']:20} -> {str(r['resolved']):20} {r['state']}")
    print(f"\nreport: {out}")
    return 0 if all(r["state"] != "UNAVAILABLE" for r in res.values()) else 1


if __name__ == "__main__":
    raise SystemExit(main())

# Scale degrees (semitones from tonic) for natural minor / major.
SCALES = {"minor": [0, 2, 3, 5, 7, 8, 10], "major": [0, 2, 4, 5, 7, 9, 11]}

# Progressions as scale-degree roots (0-based) per section role. Each tuple

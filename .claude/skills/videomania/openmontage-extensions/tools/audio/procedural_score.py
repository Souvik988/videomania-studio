"""Procedural original score — local, free, rights-clean background music.

Composes an original instrumental bed from a cue sheet using only
synthesis written in this file (band-limited wavetable pads, sub bass,
Karplus-Strong plucks, FM bells, synthesized percussion, risers, and an
algorithmic reverb). No samples, no third-party audio, no model weights,
so the provenance is simply "generated by this code with seed N".

The tempo is fitted so that narration anchor moments (reveals, CTA) fall on
downbeats where possible. Narration remains the timing master: the score
adapts to the voiceover, never the other way around.
"""


    resource_profile = ResourceProfile(cpu_cores=1, ram_mb=900, vram_mb=0, disk_mb=50)
    idempotency_key_fields = ["duration_seconds", "mood", "sections", "anchors", "bpm", "key", "scale", "seed"]
    side_effects = ["writes WAV mix, optional stems, and a .json sidecar with beat grid + provenance"]

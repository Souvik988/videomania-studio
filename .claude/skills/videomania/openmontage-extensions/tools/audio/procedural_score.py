def midi_to_hz(m: float) -> float:
    return 440.0 * 2.0 ** ((m - 69) / 12.0)


def chord_notes(tonic_midi: int, scale: str, degree: int, quality: str) -> list[int]:
    steps = SCALES[scale]
    root = tonic_midi + steps[degree % 7] + 12 * (degree // 7)
    if quality == "m":
        ivs = [0, 3, 7]
    elif quality == "M":
        ivs = [0, 4, 7]
    elif quality == "sus2":
        ivs = [0, 2, 7]
    else:  # add9
        ivs = [0, 4, 7, 14]
    return [root + i for i in ivs]


def voice_lead(prev: list[int] | None, notes: list[int], low: int = 52, high: int = 74) -> list[int]:
    """Place chord tones near the previous voicing (minimal movement)."""
    pcs = sorted({n % 12 for n in notes})
    if prev is None:
        center = (low + high) // 2
        out = []
        for pc in pcs:
            cand = [pc + 12 * k for k in range(3, 8)]
            out.append(min(cand, key=lambda c: abs(c - center)))
        return sorted(out)
    out = []
    used = set()
    for pc in pcs:
        cand = [pc + 12 * k for k in range(3, 8) if low <= pc + 12 * k <= high]
        if not cand:
            cand = [pc + 60]
        best = min(cand, key=lambda c: min(abs(c - p) for p in prev) + (5 if c in used else 0))
        used.add(best)
        out.append(best)
    return sorted(out)


# ---------------------------------------------------------------- DSP helpers

_TABLE_CACHE: dict[int, np.ndarray] = {}


def _saw_table(max_harm: int, size: int = 4096) -> np.ndarray:
    if max_harm in _TABLE_CACHE:
        return _TABLE_CACHE[max_harm]
    ph = np.arange(size) / size * 2 * np.pi
    t = np.zeros(size)
    for h in range(1, max_harm + 1):
        t += np.sin(h * ph) / h
    t /= np.max(np.abs(t))
    _TABLE_CACHE[max_harm] = t
    return t


def osc_saw(freq: float, n: int, rng: np.random.Generator, detune_cents: float = 0.0) -> np.ndarray:
    f = freq * 2 ** (detune_cents / 1200.0)
    max_h = max(1, min(48, int(11000 / f)))
    table = _saw_table(max_h)
    phase0 = rng.random()
    idx = (phase0 + np.arange(n) * f / SR) % 1.0 * len(table)
    i0 = idx.astype(np.int64)
    frac = idx - i0
    return table[i0] * (1 - frac) + table[(i0 + 1) % len(table)] * frac


def biquad_lowpass(x: np.ndarray, cutoff: float, q: float = 0.707) -> np.ndarray:
    from scipy.signal import lfilter
    w0 = 2 * np.pi * min(cutoff, SR * 0.45) / SR
    alpha = np.sin(w0) / (2 * q)
    cw = np.cos(w0)
    b = np.array([(1 - cw) / 2, 1 - cw, (1 - cw) / 2])
    a = np.array([1 + alpha, -2 * cw, 1 - alpha])
    return lfilter(b / a[0], a / a[0], x)


def biquad_highpass(x: np.ndarray, cutoff: float, q: float = 0.707) -> np.ndarray:
    from scipy.signal import lfilter
    w0 = 2 * np.pi * cutoff / SR
    alpha = np.sin(w0) / (2 * q)
    cw = np.cos(w0)
    b = np.array([(1 + cw) / 2, -(1 + cw), (1 + cw) / 2])
    a = np.array([1 + alpha, -2 * cw, 1 - alpha])
    return lfilter(b / a[0], a / a[0], x)


def bandpass(x: np.ndarray, center: float, q: float = 1.0) -> np.ndarray:
    from scipy.signal import lfilter
    w0 = 2 * np.pi * min(center, SR * 0.45) / SR
    alpha = np.sin(w0) / (2 * q)
    b = np.array([alpha, 0, -alpha])
    a = np.array([1 + alpha, -2 * np.cos(w0), 1 - alpha])
    return lfilter(b / a[0], a / a[0], x)


def adsr(n: int, a: float, d: float, s: float, r: float) -> np.ndarray:
    """Envelope of n samples; release occupies the tail."""
    na, nd, nr = int(a * SR), int(d * SR), int(r * SR)
    nr = min(nr, n)
    ns = max(0, n - na - nd - nr)
    env = np.concatenate([
        np.linspace(0, 1, max(na, 1), endpoint=False),
        np.linspace(1, s, max(nd, 1), endpoint=False),
        np.full(ns, s),
        np.linspace(s, 0, max(nr, 1)),
    ])
    if len(env) < n:
        env = np.pad(env, (0, n - len(env)))
    return env[:n]


def karplus(freq: float, n: int, rng: np.random.Generator, decay: float = 0.996, bright: float = 0.5) -> np.ndarray:
    from scipy.signal import lfilter
    period = max(2, int(round(SR / freq)))
    exc = rng.uniform(-1, 1, period)
    exc = biquad_lowpass(exc, 1500 + 6000 * bright)
    x = np.zeros(n)
    x[:period] = exc[: min(period, n)]
    a = np.zeros(period + 2)
    a[0] = 1.0
    a[period] = -decay * 0.5
    a[period + 1] = -decay * 0.5
    y = lfilter([1.0], a, x)
    return y / (np.max(np.abs(y)) + 1e-9)


def fm_bell(freq: float, n: int, ratio: float = 3.5, index: float = 2.2, decay: float = 2.5) -> np.ndarray:
    t = np.arange(n) / SR
    env = np.exp(-t * decay)
    mod = index * np.exp(-t * decay * 1.6) * np.sin(2 * np.pi * freq * ratio * t)
    return np.sin(2 * np.pi * freq * t + mod) * env


def reverb(x: np.ndarray, room: float = 0.82, damp: float = 0.3, wet: float = 0.3, seed: int = 0) -> np.ndarray:
    """Schroeder/Freeverb-style mono reverb: 6 damped combs + 3 allpasses."""
    from scipy.signal import lfilter
    combs = [1557, 1617, 1491, 1422, 1277, 1356]
    rng = np.random.default_rng(seed)
    out = np.zeros_like(x)
    for d in combs:
        d = int(d * SR / 44100) + int(rng.integers(0, 7))
        # Damping: one-pole lowpass inside feedback is approximated by
        # pre-filtering the comb input; adequate for a music bed.
        a = np.zeros(d + 1)
        a[0] = 1.0
        a[d] = -room
        out += lfilter([1.0], a, biquad_lowpass(x, 9000 * (1 - damp) + 1500))
    out /= len(combs)
    for d in (556, 441, 341):
        d = int(d * SR / 44100)
        g = 0.5
        b = np.zeros(d + 1)
        b[0] = -g
        b[d] = 1.0
        a = np.zeros(d + 1)
        a[0] = 1.0
        a[d] = -g
        out = lfilter(b, a, out)
    return x * (1 - wet) + out * wet


def place(buf: np.ndarray, sig: np.ndarray, start: int, gain: float = 1.0) -> None:
    if start >= len(buf):
        return
    end = min(len(buf), start + len(sig))
    if start < 0:
        sig = sig[-start:]
        start = 0
        end = min(len(buf), len(sig))
    buf[start:end] += sig[: end - start] * gain


# ---------------------------------------------------------------- tempo fit

def fit_tempo(anchors: list[float], base_bpm: float, duration: float, span: float = 8.0) -> tuple[float, float, float]:
    """Pick bpm (± span) and offset so anchors fall on beats, favouring downbeats.

    Returns (bpm, offset_seconds, mean_abs_error_seconds).
    """
    if not anchors:
        return base_bpm, 0.0, 0.0
    best = (1e9, base_bpm, 0.0)
    for bpm in np.arange(base_bpm - span, base_bpm + span + 0.01, 0.25):
        beat = 60.0 / bpm
        bar = beat * 4
        for off in np.linspace(0, bar, 48, endpoint=False):
            err = 0.0
            for i, a in enumerate(anchors):
                k = (a - off) / beat
                d_beat = abs(k - round(k)) * beat
                kb = (a - off) / bar
                d_bar = abs(kb - round(kb)) * bar
                w = 2.0 if i == 0 else 1.0
                err += w * min(d_bar, d_beat + 0.06)
            if err < best[0]:
                best = (err, float(bpm), float(off))
    return best[1], best[2], best[0] / max(1, len(anchors))


# ---------------------------------------------------------------- composer

class Composer:
    def __init__(self, duration: float, mood: str, sections: list[dict], anchors: list[float], seed: int,
                 bpm: float | None = None, key: str | None = None, scale: str | None = None):
        m = dict(MOODS.get(mood, MOODS["tension_to_release"]))
        self.mood_name = mood
        self.m = m
        self.duration = duration
        self.n = int(duration * SR) + SR * 3  # tail for reverb
        self.rng = np.random.default_rng(seed)
        self.seed = seed
        self.scale = scale or m["scale"]
        self.key = key or m["key"]
        self.tonic = 48 + NOTE_INDEX[self.key]  # C3-based tonic
        base_bpm = bpm or m["bpm"]
        self.bpm, self.offset, self.anchor_err = fit_tempo(anchors, base_bpm, duration) if bpm is None else (bpm, 0.0, 0.0)
        self.beat = 60.0 / self.bpm
        self.bar = self.beat * 4
        self.sections = sections or [{"start": 0, "end": duration, "role": "build", "energy": 0.5}]
        self.anchors = anchors

    def _section_at(self, t: float) -> dict:
        for s in self.sections:
            if s["start"] <= t < s["end"]:
                return s
        return self.sections[-1]

    def bar_times(self) -> list[float]:
        first = self.offset - self.bar * np.ceil(self.offset / self.bar)
        times = []
        t = first
        while t < self.duration + self.bar:
            times.append(t)
            t += self.bar
        return times

    def render(self) -> dict[str, np.ndarray]:
        n = self.n
        stems = {k: np.zeros(n) for k in ("pad", "bass", "pluck", "drums", "fx")}
        bars = self.bar_times()
        prev_voicing = None
        prog_pos: dict[str, int] = {}
        chords_log = []
        for bi, bt in enumerate(bars):
            sec = self._section_at(max(bt, 0.0) + self.bar * 0.5)
            role = sec.get("role", "build")
            energy = float(sec.get("energy", 0.5))
            prog = PROGRESSIONS[self.scale].get(role, PROGRESSIONS[self.scale]["build"])
            idx = prog_pos.get(role, 0)
            prog_pos[role] = idx + 1
            degree, quality = prog[idx % len(prog)]
            notes = chord_notes(self.tonic, self.scale, degree, quality)
            voicing = voice_lead(prev_voicing, notes)
            prev_voicing = voicing
            chords_log.append({"bar_start": round(bt, 3), "role": role, "degree": degree, "quality": quality, "voicing": voicing})
            start = int(bt * SR)
            self._pad(stems["pad"], start, voicing, energy)
            self._bass(stems["bass"], start, notes[0] - 12, energy)
            self._pluck(stems["pluck"], start, voicing, energy)
            self._drums(stems["drums"], start, energy, role)
        for a in self.anchors:
            self._riser_and_hit(stems["fx"], a, self.tonic + 24)
        # Section dynamics: an energy-following gain curve (smoothed over
        # ~0.8 s) so quiet sections genuinely sit back and reveals open up.
        env = np.zeros(n)
        for s_ in self.sections:
            a_, b_ = int(s_["start"] * SR), int(min(s_["end"], self.duration + 3) * SR)
            env[a_:b_] = 0.22 + 0.78 * float(s_.get("energy", 0.5))
        env[int(self.sections[-1]["end"] * SR):] = env[max(0, int(self.sections[-1]["end"] * SR) - 1)]
        k = int(0.8 * SR)
        env = np.convolve(env, np.ones(k) / k, mode="same")
        for key_ in stems:
            if key_ != "fx":
                stems[key_] *= env
        # intro fade-in and final ring-out
        fade_in = int(min(1.5, self.duration * 0.1) * SR)
        end = int(self.duration * SR)
        for k in stems:
            stems[k][:fade_in] *= np.linspace(0, 1, fade_in) ** 2
            tail = np.linspace(1, 0, int(2.0 * SR))
            seg = stems[k][end - int(1.0 * SR): end - int(1.0 * SR) + len(tail)]
            seg *= tail[: len(seg)]
            stems[k][end - int(1.0 * SR) + len(tail):] = 0
        self.chords_log = chords_log
        return stems

    def _pad(self, buf, start, voicing, energy):
        n = int(self.bar * SR) + int(1.2 * SR)
        sig = np.zeros(n)
        for note in voicing:
            f = midi_to_hz(note)
            for det in (-7, 0, 7):
                sig += osc_saw(f, n, self.rng, det) / 3
        sig /= max(1, len(voicing))
        cutoff = 1400 + 5200 * energy * self.m["bright"]
        sig = biquad_lowpass(sig, cutoff)
        sig = biquad_highpass(sig, 160)
        env = adsr(n, 0.6, 0.4, 0.85, 1.2)
        place(buf, sig * env, start, 0.34 + 0.12 * energy)

    def _bass(self, buf, start, note, energy):
        f = midi_to_hz(note)
        if energy < 0.35:
            pattern = [(0, 4.0)]
        elif energy < 0.7:
            pattern = [(0, 1.5), (2, 1.5)]
        else:
            pattern = [(0, 0.45), (0.75, 0.2), (1.5, 0.45), (2, 0.45), (2.75, 0.2), (3.5, 0.45)]
        for beat_pos, length in pattern:
            n = int(length * self.beat * SR) + int(0.05 * SR)
            t = np.arange(n) / SR
            sig = np.sin(2 * np.pi * f * t) + 0.25 * np.sin(2 * np.pi * 2 * f * t)
            sig = np.tanh(sig * 1.6)
            sig = biquad_lowpass(sig, 420)
            env = adsr(n, 0.008, 0.08, 0.8, 0.06)
            place(buf, sig * env, start + int(beat_pos * self.beat * SR), 0.13 + 0.05 * energy)

    def _pluck(self, buf, start, voicing, energy):
        density = energy * self.m["pluck"]
        if density < 0.2:
            return
        steps = 8 if density < 0.6 else 16
        step_len = self.bar / steps
        tones = [v + 12 for v in voicing]
        pattern = [0, 2, 1, 2, 0, 2, 1, 3] if steps == 8 else [0, 2, 1, 2, 3, 2, 1, 2, 0, 2, 1, 2, 3, 1, 2, 1]
        for i in range(steps):
            if steps == 16 and self.rng.random() > 0.55 + 0.4 * density:
                continue
            tone = tones[pattern[i] % len(tones)]
            n = int(0.9 * SR)
            sig = karplus(midi_to_hz(tone), n, self.rng, decay=0.994, bright=0.35 + 0.4 * energy)
            acc = 1.0 if i % 4 == 0 else 0.7
            place(buf, sig, start + int(i * step_len * SR), 0.17 * acc * (0.6 + 0.4 * energy))

    def _drums(self, buf, start, energy, role):
        dens = energy * self.m["drums"]
        if dens < 0.3:
            return
        for b in range(4):
            bt = start + int(b * self.beat * SR)
            if b in (0, 2) or (dens > 0.75 and b == 3 and self.rng.random() < 0.3):
                place(buf, self._kick(), bt, 0.30 * min(1.0, dens + 0.2))
            if dens > 0.5 and b in (1, 3):
                place(buf, self._clap(), bt, 0.22 * dens)
            hats = 2 if dens < 0.8 else 4
            for h in range(hats):
                place(buf, self._hat(), bt + int(h * self.beat / hats * SR), (0.16 if h % 2 else 0.11) * dens)

    def _kick(self):
        n = int(0.45 * SR)
        t = np.arange(n) / SR
        f = 45 + 95 * np.exp(-t * 30)
        ph = 2 * np.pi * np.cumsum(f) / SR
        return np.sin(ph) * np.exp(-t * 7) + 0.15 * self.rng.uniform(-1, 1, n) * np.exp(-t * 120)

    def _clap(self):
        n = int(0.25 * SR)
        t = np.arange(n) / SR
        noise = bandpass(self.rng.uniform(-1, 1, n), 1500, 0.8)
        env = np.exp(-t * 22)
        for d in (0.0, 0.012, 0.024):
            env += 0.6 * np.exp(-np.clip(t - d, 0, None) * 140) * (t >= d)
        return noise * env * 0.6

    def _hat(self):
        n = int(0.06 * SR)
        t = np.arange(n) / SR
        return biquad_highpass(self.rng.uniform(-1, 1, n), 7000) * np.exp(-t * 70)

    def _riser_and_hit(self, buf, t_hit, bell_note):
        rise = 1.6
        n = int(rise * SR)
        t = np.arange(n) / SR
        noise = self.rng.uniform(-1, 1, n)
        # sweep by stitching short bandpassed chunks
        out = np.zeros(n)
        chunk = int(0.04 * SR)
        for i in range(0, n, chunk):
            c = 300 * (25 ** (i / n))
            out[i:i + chunk] = bandpass(noise[i:i + chunk + 256], c, 2.0)[: min(chunk, n - i)]
        out *= (t / rise) ** 2.2
        place(buf, out, int((t_hit - rise) * SR), 0.10)
        m = int(2.6 * SR)
        tt = np.arange(m) / SR
        sub = np.sin(2 * np.pi * np.cumsum(70 * np.exp(-tt * 3) + 32) / SR) * np.exp(-tt * 3.5)
        bell = fm_bell(midi_to_hz(bell_note), m) * 0.5 + fm_bell(midi_to_hz(bell_note + 7), m, decay=3.0) * 0.3
        place(buf, sub * 0.5 + bell * 0.35, int(t_hit * SR), 0.6)


def write_wav(path: Path, data: np.ndarray) -> None:
    """Write float stereo/mono array (-1..1) as 24-bit PCM WAV."""
    path.parent.mkdir(parents=True, exist_ok=True)
    if data.ndim == 1:
        data = data[:, None]
    clipped = np.clip(data, -1.0, 1.0)
    ints = (clipped * (2 ** 23 - 1)).astype(np.int32)
    raw = bytearray()
    b = ints.astype("<i4").tobytes()
    # pack 4-byte little-endian ints to 3 bytes
    arr = np.frombuffer(b, dtype=np.uint8).reshape(-1, 4)[:, :3]
    raw = arr.tobytes()
    with wave.open(str(path), "wb") as w:
        w.setnchannels(data.shape[1])
        w.setsampwidth(3)
        w.setframerate(SR)
        w.writeframes(raw)


def stereoize(mono: np.ndarray, width: float, seed: int) -> np.ndarray:
    """Haas-free stereo spread: complementary short delays mixed at low level."""
    d = int(0.011 * SR) + seed % 5
    l = mono.copy()
    r = mono.copy()
    l[d:] += width * mono[:-d]
    r[d * 2:] -= width * 0.6 * mono[:-d * 2]
    return np.stack([l, r], axis=1)


